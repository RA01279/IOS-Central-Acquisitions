import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(readFileSync(new URL("../lib/asset-transactions.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText;
const { saleComparison, transactionUpdate, seededAssetStatus } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const owned = { status: "owned", purchase_price: 2000000, purchased_on: "2020-01-01", sale_price: null, sold_on: null, acquisition_costs: 100000, selling_costs: null };
const sold = { ...owned, status: "sold", sale_price: 3000000, sold_on: "2026-01-01", selling_costs: 150000 };
const comparison = saleComparison(sold);
assert.equal(comparison.change, 1000000);
assert.equal(comparison.percent, 50);
assert.equal(comparison.basis, 2100000);
assert.equal(comparison.proceeds, 2850000);
assert.equal(comparison.netChange, 750000);
assert.ok(Math.abs(comparison.netPercent - 35.714285714) < 0.000001);
assert.equal(saleComparison({ ...sold, sale_price: 1900000 }).netChange, -350000);
assert.equal(saleComparison({ ...sold, selling_costs: null }).netChange, null);
assert.equal(saleComparison({ ...sold, acquisition_costs: 0, selling_costs: 0 }).netChange, 1000000);
assert.equal(saleComparison({ ...sold, purchase_price: null }), null);
assert.equal(saleComparison(owned), null);
assert.deepEqual(transactionUpdate({ status: "sold", salePrice: "$3,000,000.00", soldOn: "2026-01-01", sellingCosts: "150,000" }, owned), { status: "sold", sale_price: 3000000, sold_on: "2026-01-01", selling_costs: 150000 });
assert.deepEqual(transactionUpdate({ purchasePrice: "2,100,000" }, sold), { purchase_price: 2100000 });
assert.deepEqual(transactionUpdate({ status: "owned", salePrice: "", soldOn: "", sellingCosts: "" }, sold), { status: "owned", sale_price: null, sold_on: null, selling_costs: null });
for (const value of ["junk", "0", "-100", "12,34", "1.234", "Infinity", "1e6", true, {}]) assert.throws(() => transactionUpdate({ purchasePrice: value }, owned));
assert.equal(transactionUpdate({ acquisitionCosts: "0" }, owned).acquisition_costs, 0);
assert.throws(() => transactionUpdate({ acquisitionCosts: "-1" }, owned));
assert.throws(() => transactionUpdate({ status: "sold" }, owned));
assert.throws(() => transactionUpdate({ status: "owned" }, sold));
assert.throws(() => transactionUpdate({ soldOn: "2026-02-30" }, sold));
assert.throws(() => transactionUpdate({ purchasedOn: "2027-01-01" }, sold));
assert.equal(seededAssetStatus({ status: "sold" }, false), "sold");
assert.equal(seededAssetStatus({ status: "under_contract" }, false), "under_contract");
assert.equal(seededAssetStatus({ status: "owned" }, true), "sold");
console.log("Asset transaction calculations, validation, partial edits and seed preservation passed.");
